"""Signing for shared pin baselines.

The pin file is a trust anchor, and a trust anchor that anyone can rewrite is not one.
A local ``~/.pindrift/pins.json`` is only as protected as the user's home directory,
but a baseline committed to a repository leaves the machine entirely. This module gives
that file a signature so a teammate can tell an approved baseline from an edited one.

The signature is HMAC-SHA256 over the canonicalised pin document. Ed25519 would prove
*who* signed, but it does not exist in the standard library, and adding
``cryptography`` to a tool people are asked to trust is a worse trade than losing
authorship identity. A shared secret proves the file was written by somebody holding
the key; that is the property a shared baseline actually needs.

Key sources, in order:

1. ``PINDRIFT_TRUST_KEY`` -- 64 hex characters. Use this in CI and anywhere the key
   can live in a secret store rather than next to the file it protects.
2. ``$PINDRIFT_HOME/trust.key`` -- generated by ``pindrift trust init``, mode 0600.

A key file beside ``pins.json`` protects a copy of the baseline that travels elsewhere;
it does not protect the local file from someone who can already read the key. Be
honest about that in the threat model.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import os
import secrets
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ALGORITHM = "hmac-sha256"
ENV_KEY = "PINDRIFT_TRUST_KEY"
KEY_BYTES = 32
KEY_FILENAME = "trust.key"


class TrustError(ValueError):
    """The key or the signed document is unusable."""


@dataclass(frozen=True)
class Verification:
    """Outcome of checking one document's signature.

    ``ok`` is false for every state other than ``valid``. In particular a missing key
    is ``no_key``, never success: the same rule as ``State.UNKNOWN``.
    """

    ok: bool
    state: str  # valid | invalid | unsigned | no_key
    detail: str


def key_path() -> Path:
    # Imported lazily: store imports this module to sign on save, so a top-level
    # import here would be circular. By call time store is fully loaded.
    from . import store

    return store.home() / KEY_FILENAME


def _decode(value: str, source: str) -> bytes:
    try:
        key = bytes.fromhex(value.strip())
    except ValueError as exc:
        raise TrustError(f"{source} is not valid hex") from exc
    if len(key) < KEY_BYTES:
        raise TrustError(
            f"{source} is {len(key)} bytes; a trust key must be at least {KEY_BYTES} "
            f"bytes ({KEY_BYTES * 2} hex characters)"
        )
    return key


def _env_key() -> bytes | None:
    value = os.environ.get(ENV_KEY)
    if value is None or not value.strip():
        return None
    return _decode(value, ENV_KEY)


def _file_key() -> bytes | None:
    path = key_path()
    if not path.is_file():
        return None
    try:
        value = path.read_text(encoding="utf-8-sig").strip()
    except OSError as exc:
        raise TrustError(f"cannot read trust key {path}: {exc}") from exc
    return _decode(value, f"trust key {path}")


def load_key() -> bytes | None:
    """Return the signing key, or ``None`` when none is configured.

    A malformed key raises instead of being ignored: silently treating a broken key as
    absent would turn an intentional signature into an unsigned file.
    """
    env = _env_key()
    return env if env is not None else _file_key()


def ensure_key(*, force: bool = False) -> tuple[bytes, Path | None, bool]:
    """Load or create a key. Returns ``(key, path, created)``.

    ``path`` is ``None`` when the key came from the environment, because nothing was
    written to disk. An environment key always wins, even with ``force``: CI should not
    start generating its own key just because a stray ``trust init`` ran.
    """
    env = _env_key()
    if env is not None:
        return env, None, False

    path = key_path()
    if path.is_file() and not force:
        existing = _file_key()
        if existing is None:
            raise TrustError(f"trust key {path} disappeared while reading it")
        return existing, path, False

    path.parent.mkdir(parents=True, exist_ok=True)
    key = secrets.token_bytes(KEY_BYTES)
    path.write_text(key.hex() + "\n", encoding="utf-8")
    try:
        os.chmod(path, 0o600)
    except OSError:
        # Windows may not support the mode; the file content is still correct.
        pass
    return key, path, True


def canonical_bytes(payload: dict[str, Any]) -> bytes:
    """Stable bytes for signing.

    The signature field is excluded, and the document is canonicalised rather than
    hashed as written: reformatting the JSON must not invalidate a signature, changing
    a value must.
    """
    body = {k: v for k, v in payload.items() if k != "signature"}
    return json.dumps(body, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode(
        "utf-8"
    )


def sign(payload: dict[str, Any], key: bytes | None = None) -> dict[str, str] | None:
    """Return the signature block for ``payload``, or ``None`` without a key."""
    signer = key if key is not None else load_key()
    if signer is None:
        return None
    digest = hmac.new(signer, canonical_bytes(payload), hashlib.sha256).hexdigest()
    return {"alg": ALGORITHM, "value": digest}


def verify(payload: dict[str, Any], key: bytes | None = None) -> Verification:
    """Check a document's signature. Never treats "cannot check" as success."""
    if not isinstance(payload, dict):
        return Verification(False, "invalid", "baseline is not a JSON object")

    block = payload.get("signature")
    if not isinstance(block, dict):
        return Verification(False, "unsigned", "baseline is not signed")
    alg = block.get("alg")
    value = block.get("value")
    if alg != ALGORITHM or not isinstance(value, str):
        return Verification(
            False, "invalid", f"baseline signature is malformed (expected {ALGORITHM})"
        )

    signer = key if key is not None else load_key()
    if signer is None:
        return Verification(
            False,
            "no_key",
            f"no trust key available; set {ENV_KEY} to the key that signed this baseline",
        )

    expected = hmac.new(signer, canonical_bytes(payload), hashlib.sha256).hexdigest()
    if not hmac.compare_digest(expected, value):
        return Verification(
            False,
            "invalid",
            "signature mismatch: the baseline was modified after signing, "
            "or it was signed with a different key",
        )
    count = len(payload.get("pins") or {})
    return Verification(True, "valid", f"signature ok ({count} server(s))")
